  function rng(seed) { // mulberry32
    var a = seed >>> 0;
    return function () { a = (a + 0x6D2B79F5) >>> 0; var t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  }
  function pad(n) { return (n < 10 ? '0' : '') + n; }
  function dateIn(rand, ym, months) {
    var y = +ym.slice(0, 4), m = +ym.slice(5, 7) - 1 + Math.floor(rand() * months), d = 1 + Math.floor(rand() * 28);
    y += Math.floor(m / 12); m = m % 12;
    var s = y + '-' + pad(m + 1) + '-' + pad(d);
    return s > '2026-09-30' ? '2026-09-' + pad(Math.min(d, 30)) : s;
  }
  function pick(rand, list) { return list[Math.floor(rand() * list.length)]; }
  function weighted(rand, items) {
    var sum = items.reduce(function (s, x) { return s + x.w; }, 0), r = rand() * sum;
    for (var i = 0; i < items.length; i++) { r -= items[i].w; if (r <= 0) return items[i]; }
    return items[items.length - 1];
  }

